# 加工站（取代 models/機庫/整備庫_11_加工站.glb）。舊模型在遊戲裡縮放 70：寬 7.1、深 7.1、高 11.3。兩根立柱、頂上一個橫樑罩、中間一個往前伸的工作台，台上兩支主軸，旁邊一根管子。
# 新的尺寸、朝向一樣（工作台朝 +z）。沒有會動的部分。
#   blender -b --factory-startup --python build_station.py -- [--no-bake] [--no-export] [--compare]
# 零件表：Frame 兩根立柱、柱腳、頂上的橫樑罩；Carriage 柱子之間的滑座、兩支主軸與刀具；Table 工作台、托架、T 型槽、切屑盤；
#         Services 後面的油壓箱、側邊的管子、控制盤
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hgkit import *

M = Machine('station', '整備庫_34_加工站', tex=1024, yaw=90)      # 舊模型的工作台朝 +x（零件照 +z 建，最後整個轉 90°，朝向跟舊模型一樣）
CX, TY = 2.3, 4.3                                      # 立柱的 |x|、工作台面的高度

P = Pal()
for s in (1, -1):
    x = s * CX
    box(P['white'], x - 0.55, x + 0.55, 0.3, 9.4, -1.1, 0.3)
    box(P['steel'], x - 0.85, x + 0.85, 0.0, 0.3, -1.6, 0.9)            # 柱腳
    box(P['hazard'], x - 0.55, x + 0.55, 0.3, 1.1, 0.3, 0.312)
    box(P['navy'], min(s * (CX + 0.55), s * (CX + 0.562)), max(s * (CX + 0.55), s * (CX + 0.562)), 5.0, 8.6, -0.8, 0.0)
    box(P['steel'], x - 0.2, x + 0.2, 1.4, 8.9, 0.3, 0.38)              # 滑座的導軌
    for bx, bz in ((0.65, 0.6), (-0.65, 0.6), (0.65, -1.3), (-0.65, -1.3)):
        cylY(P['steel'], x + bx, bz, 0.3, 0.36, 0.07, None, 6)
plate(P['white'], [(-3.2, 9.4), (3.2, 9.4), (3.5, 9.8), (3.5, 10.9), (3.1, 11.3), (-3.1, 11.3), (-3.5, 10.9), (-3.5, 9.8)], -1.5, 0.9)     # 橫樑罩
box(P['navy'], -2.4, 2.4, 9.9, 10.8, 0.9, 0.914)
box(P['glow'], -1.8, 1.8, 10.32, 10.38, 0.914, 0.922)
M.part('Frame', 'Root', P)
P = Pal()
box(P['navy'], -CX + 0.55, CX - 0.55, 4.9, 6.6, -0.9, 0.5)              # 滑座
box(P['steel'], -CX - 0.3, CX + 0.3, 5.3, 6.2, 0.38, 0.6)               # 夾住兩根導軌的橫板
for x in (-0.8, 0.8):
    cylZ(P['white'], x, 5.6, 0.5, 1.5, 0.42, 24)                        # 主軸頭
    cylZ(P['steel'], x, 5.6, 1.5, 1.75, 0.3, 20)
    cylZ(P['chrome'], x, 5.6, 1.75, 2.9, 0.09, 12)                      # 刀具
    cylZ(P['orange'], x, 5.6, 1.48, 1.52, 0.44, 24)
for x in (-CX + 0.75, CX - 0.75):                                       # 升降的兩支螺桿
    cylY(P['chrome'], x, -0.4, 6.6, 9.4, 0.09, None, 12)
M.part('Carriage', 'Root', P)
P = Pal()
box(P['steel'], -2.2, 2.2, TY - 0.3, TY, 0.6, 3.6)
for x in (-1.4, -0.7, 0.0, 0.7, 1.4):                                   # T 型槽
    box(P['rubber'], x - 0.05, x + 0.05, TY - 0.02, TY + 0.003, 0.7, 3.5)
box(P['hazard'], -2.2, 2.2, TY - 0.3, TY - 0.05, 3.6, 3.612)
for x in (-1.9, 1.9):                                                   # 托架
    plate(P['white'], [(0.3, 1.0), (0.9, 1.0), (3.5, TY - 0.3), (0.3, TY - 0.3)], x - 0.1, x + 0.1, Ry(-pi / 2) @ Rz(0))
box(P['steel'], -2.5, 2.5, 0.0, 0.5, 0.95, 3.4)                         # 切屑盤
box(P['rubber'], -2.4, 2.4, 0.5, 0.503, 1.05, 3.3)
M.part('Table', 'Root', P)
P = Pal()
box(P['white'], -1.7, 1.7, 0.0, 3.4, -3.5, -1.7)                        # 油壓箱
box(P['navy'], -1.3, 1.3, 0.5, 2.9, -3.514, -3.5)
for i in range(6):
    box(P['steel'], -1.1, 1.1, 0.8 + i * 0.32, 0.92 + i * 0.32, -3.53, -3.514)
cylY(P['steel'], -1.0, -2.6, 3.4, 3.9, 0.3, None, 16)                   # 油箱蓋與馬達
cylY(P['navy'], 0.6, -2.6, 3.4, 4.5, 0.45, None, 20)
hose(P['steel'], [V(-CX - 0.55, 5.8, -0.4), V(-3.3, 5.8, -0.4), V(-3.45, 5.2, -0.4), V(-3.45, 0.5, -0.4), V(-3.45, 0.14, -0.9), V(-2.9, 0.14, -2.4), V(-1.7, 0.14, -2.6)], 0.14, 10)     # 側邊的管子
box(P['navy'], CX + 0.55, CX + 0.9, 3.6, 5.2, -0.6, 0.2)                # 控制盤
box(P['glow'], CX + 0.9, CX + 0.908, 4.4, 5.0, -0.45, 0.05)
for i in range(3):
    cylX(P['orange'], CX + 0.9, CX + 0.96, 3.9, -0.4 + i * 0.22, 0.06, None, 10)
M.part('Services', 'Root', P)

M.finish(dict(size=[7.1, 11.3, 7.1], table_y=TY))
if '--compare' in ARGS:
    M.compare('11_加工站', 70, dist=0.95)
